import { LogEntry, WeeklyReport, WeeklyReportSections } from '../types';

/**
 * 自動從多筆日常記錄中聚類出標準 Advisor Meeting 四大區塊 + 實驗室行政貢獻第五區塊
 */
export function generateWeeklyReport(
  logs: LogEntry[],
  startDate: string,
  endDate: string,
  includeAdmin: boolean = true
): WeeklyReport {
  const sections: WeeklyReportSections = {
    whatWasDone: [],
    blockers: [],
    discussionPoints: [],
    nextSteps: [
      '推進後續實驗驗證與消融實驗對照',
      '彙整本週所得數據並繪製對比折線圖',
      '針對 Advisor 建議方向進行第二版程式重構',
    ],
    adminTasks: [],
  };

  logs.forEach((log) => {
    switch (log.category) {
      case 'progress':
        sections.whatWasDone.push(log.content);
        break;
      case 'blocker':
        sections.blockers.push(log.content);
        break;
      case 'discussion':
        sections.discussionPoints.push(log.content);
        break;
      case 'idea':
        // 靈感可依情境加入討論或下週規劃
        sections.discussionPoints.push(`[靈感探討] ${log.content}`);
        break;
      case 'admin':
        if (!sections.adminTasks) sections.adminTasks = [];
        sections.adminTasks.push(log.content);
        break;
    }
  });

  const rawMarkdown = formatToMarkdown(sections, startDate, endDate, includeAdmin);

  return {
    id: `report-${Date.now()}`,
    title: `Advisor Meeting 週報 (${startDate} ~ ${endDate})`,
    startDate,
    endDate,
    sections,
    rawMarkdown,
    status: 'draft',
    includeAdmin,
  };
}

/**
 * 轉為標準學術 Markdown 格式
 */
export function formatToMarkdown(
  sections: WeeklyReportSections,
  startDate: string,
  endDate: string,
  includeAdmin: boolean = true
): string {
  const formatList = (items: string[]) =>
    items.length > 0 ? items.map((i) => `- ${i}`).join('\n') : '- 暫無記錄';

  let md = `# Advisor Meeting 週報 - Reseaver LabPulse

> 統計週期：${startDate} ~ ${endDate}

## 一、本週推進成果 (What was done)
${formatList(sections.whatWasDone)}

## 二、遭遇問題與卡點 (Challenges & Blockers)
${formatList(sections.blockers)}

## 三、預計與教授討論事項 (Advisor Discussion Points)
${formatList(sections.discussionPoints)}

## 四、下週目標與規劃 (Next Steps)
${formatList(sections.nextSteps)}`;

  if (includeAdmin && sections.adminTasks && sections.adminTasks.length > 0) {
    md += `\n\n## 五、實驗室行政與專案貢獻 (Lab Administration & Projects)
${formatList(sections.adminTasks)}`;
  }

  md += `\n\n---\n*Generated by Reseaver LabPulse*
`;
  return md;
}
